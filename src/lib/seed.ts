const MEAL_TIMES: Record<MealType, string> = {
  breakfast: "08:15",
  lunch: "13:20",
  dinner: "19:05",
  snack: "16:10",
  extra: "21:00",
};

function entriesFromCombo(
  combo: Combo,
  byName: Map<string, Product>,
  date: string,
  meal: MealType
): MealEntry[] {
  const out: MealEntry[] = [];
  for (const [name, grams] of combo) {
    if (grams <= 0) continue;
    const p = byName.get(name);
    if (!p) continue;
    const t = scaleNutrition(p, grams);
    out.push({
      id: uid("e"),
      date,
      meal,
      time: MEAL_TIMES[meal],
      kind: "product",
      refId: p.id,
      name: p.name,
      grams,
      kcal: Math.round(t.kcal),
      protein: Math.round(t.protein * 10) / 10,
      fat: Math.round(t.fat * 10) / 10,
      carbs: Math.round(t.carbs * 10) / 10,
    });
  }
  return out;
}

export function buildDemo(profile: Profile, products: Product[]): {
  entries: MealEntry[];
  weights: WeightPoint[];
  activities: ActivityEntry[];
} {
  const rand = mulberry32(20260217);
  const byName = new Map(products.map((p) => [p.name, p]));
  const entries: MealEntry[] = [];
  const activities: ActivityEntry[] = [];
  const DAYS = 20;

  for (let i = DAYS; i >= 1; i--) {
    const date = addDaysKey(todayKey(), -i);
    const weekend = [0, 6].includes(new Date(date).getDay());
    const pick = <T,>(arr: T[]): T => arr[Math.floor(rand() * arr.length)];

    const combos: Array<[MealType, Combo]> = [
      ["breakfast", pick(BREAKFASTS)],
      ["lunch", pick(LUNCHES)],
      ["dinner", pick(DINNERS)],
    ];

    if (rand() > 0.25) combos.push(["snack", pick(SNACKS)]);
    if (weekend && rand() > 0.5) combos.push(["snack", [["Шоколад тёмный 70%", 20]]]);

    for (const [meal, combo] of combos) {
      entries.push(...entriesFromCombo(combo, byName, date, meal));
    }

    if (rand() > 0.45) {
      const minutes = 30 + Math.floor(rand() * 40);
      const labels = ["Ходьба", "Бег", "Велосипед", "Тренировка в зале", "Плавание"];
      const mets = [4, 8.5, 7, 6, 7];
      const idx = Math.floor(rand() * labels.length);
      const kcal = Math.round((mets[idx] * profile.weightKg * minutes) / 60);
      activities.push({
        id: uid("a"),
        date,
        label: labels[idx],
        minutes,
        kcal,
      });
    }
  }

  // Вес: тренд вниз с небольшими колебаниями
  const weights: WeightPoint[] = [];
  for (let i = 30; i >= 0; i -= 3) {
    const target = profile.weightKg + (i / 30) * 2.1;
    const kg = Math.round((target + (rand() - 0.5) * 0.5) * 10) / 10;
    weights.push({ date: addDaysKey(todayKey(), -i), kg });
  }
  weights.push({ date: todayKey(), kg: profile.weightKg });

  return { entries, weights, activities };
}
