/* ---------------- Рецепты ---------------- */
function ingredient(p: Product, grams: number): Ingredient {
  const t = scaleNutrition(p, grams);
  return {
    productId: p.id,
    name: p.name,
    grams,
    kcal: Math.round(t.kcal),
    protein: Math.round(t.protein * 10) / 10,
    fat: Math.round(t.fat * 10) / 10,
    carbs: Math.round(t.carbs * 10) / 10,
  };
}

function findProducts(
  names: Array<[string, number]>,
  byName: Map<string, Product>
): Ingredient[] {
  return names.map(([name, grams]) => {
    const p = byName.get(name);
    if (!p) throw new Error(`Seed: продукт не найден: ${name}`);
    return ingredient(p, grams);
  });
}

